// Build the deterministic OverleafPlus v3.3 additive CSS overlay.
import { createHash } from "node:crypto"
import { mkdirSync, readFileSync, writeFileSync } from "node:fs"
import { dirname, join } from "node:path"
import { fileURLToPath } from "node:url"

const root = dirname(fileURLToPath(import.meta.url))
const basePath = join(root, "..", "v3.2", "dist", "hln-ui-system-v3.2.css")
const sourcePath = join(root, "src", "overleafplus.css")
const palettePath = join(root, "src", "palettes.json")
const distPath = join(root, "dist")
const artifactPath = join(distPath, "hln-ui-system-v3.3.css")
const provenancePath = join(distPath, "provenance.json")
const sha256 = (bytes) => createHash("sha256").update(bytes).digest("hex")

const base = readFileSync(basePath)
const source = Buffer.from(readFileSync(sourcePath, 'utf8').replace(/\r\n?/g, '\n'), 'utf8')
const sourceText = source.toString("utf8")
const variant = "overleafplus-v33"
const palettes = JSON.parse(readFileSync(palettePath, "utf8"))
const themeIds = ["linear-obsidian", "linear-platinum", "linear-amber", "linear-paper", "linear-emerald", "linear-mono"]
const roles = ["writing", "analysis", "review", "media"]
if (JSON.stringify(Object.keys(palettes)) !== JSON.stringify(themeIds)) {
  throw new Error("Palette source must contain exactly the six existing v3.2 themes in canonical order")
}
for (const [theme, values] of Object.entries(palettes)) {
  if (JSON.stringify(Object.keys(values)) !== JSON.stringify(roles) ||
      Object.values(values).some(value => !/^#[0-9A-F]{6}$/.test(value))) {
    throw new Error(`Invalid research-category palette: ${theme}`)
  }
}
const paletteSource = Buffer.from(`${JSON.stringify(palettes, null, 2)}\n`, "utf8")
const paletteCSS = themeIds.map(theme =>
  `[data-hln-ui-variant='${variant}'][data-hln-theme='${theme}'] {\n` +
  roles.map(role => `  --hln-v33-${role}: ${palettes[theme][role]};`).join("\n") + "\n}\n"
).join("\n")
if (!sourceText.includes(`[data-hln-ui-variant='${variant}']`)) {
  throw new Error(`Overlay source must scope its selectors to ${variant}`)
}
if (sourceText.includes("[data-hln-theme") || sourceText.includes("[data-theme=")) {
  throw new Error("Only the structured palette generator may select existing theme IDs")
}
if (/--hln-ui-[\w-]+\s*:/.test(sourceText)) throw new Error("The overlay must not redefine v3.2 tokens")

const banner = "/* KalciriteUI v3.3 OverleafPlus additive overlay. Do not edit; generated by build.mjs. */\n"
const artifact = Buffer.from(banner + paletteCSS + "\n" + sourceText.replace(/\n*$/, "\n"), "utf8")
const provenance = {
  baseSHA: sha256(base),
  sourceSHA: sha256(source),
  paletteSHA: sha256(paletteSource),
  artifactSHA: sha256(artifact),
  variant,
  schema: "kalcirite-ui-overlay-provenance/v1",
  version: "3.3.5",
}

mkdirSync(distPath, { recursive: true })
writeFileSync(artifactPath, artifact)
writeFileSync(provenancePath, `${JSON.stringify(provenance, null, 2)}\n`, "utf8")
console.log("v3.3 additive overlay assembled; bytes:", artifact.byteLength)
