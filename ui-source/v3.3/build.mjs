// Build the deterministic OverleafPlus v3.3 additive CSS overlay.
import { createHash } from "node:crypto"
import { mkdirSync, readFileSync, writeFileSync } from "node:fs"
import { dirname, join } from "node:path"
import { fileURLToPath } from "node:url"

const root = dirname(fileURLToPath(import.meta.url))
const basePath = join(root, "..", "v3.2", "dist", "hln-ui-system-v3.2.css")
const sourcePath = join(root, "src", "overleafplus.css")
const distPath = join(root, "dist")
const artifactPath = join(distPath, "hln-ui-system-v3.3.css")
const provenancePath = join(distPath, "provenance.json")
const sha256 = (bytes) => createHash("sha256").update(bytes).digest("hex")

const base = readFileSync(basePath)
const source = Buffer.from(readFileSync(sourcePath, 'utf8').replace(/\r\n?/g, '\n'), 'utf8')
const sourceText = source.toString("utf8")
const variant = "overleafplus-v33"
if (!sourceText.includes(`[data-hln-ui-variant='${variant}']`)) {
  throw new Error(`Overlay source must scope its selectors to ${variant}`)
}
if (sourceText.includes("[data-hln-theme") || sourceText.includes("[data-theme=")) {
  throw new Error("The additive overlay must not define or select theme IDs")
}

const banner = "/* KalciriteUI v3.3 OverleafPlus additive overlay. Do not edit; generated by build.mjs. */\n"
const artifact = Buffer.from(banner + sourceText.replace(/\n*$/, "\n"), "utf8")
const provenance = {
  baseSHA: sha256(base),
  sourceSHA: sha256(source),
  artifactSHA: sha256(artifact),
  variant,
  schema: "kalcirite-ui-overlay-provenance/v1",
  version: "3.3.0",
}

mkdirSync(distPath, { recursive: true })
writeFileSync(artifactPath, artifact)
writeFileSync(provenancePath, `${JSON.stringify(provenance, null, 2)}\n`, "utf8")
console.log("v3.3 additive overlay assembled; bytes:", artifact.byteLength)
