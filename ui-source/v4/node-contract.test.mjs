test("v4 skin allowlist rejects unknown tokens and invalid colours", () => {
  assert.ok(HLN_V4_SKIN_TOKENS.includes("--hln-ui-accent"))
  assert.ok(HLN_V4_SKIN_TOKENS.includes("--hln-ui-on-accent"))
  assert.ok(!HLN_V4_SKIN_TOKENS.includes("--hln-ui-radius-lg"))
  const skin = createHlnSkin({ id: "demo-skin", tokens: { "--hln-ui-accent": "#123456" } })
  assert.equal(skin.id, "demo-skin")
  assert.equal(skin.tokens["--hln-ui-accent"], "#123456")
  assert.throws(() => createHlnSkin({ id: "bad id!", tokens: {} }), TypeError)
  assert.throws(() => createHlnSkin({ id: "ok", tokens: { "--hln-ui-radius-lg": "8px" } }), TypeError)
  assert.throws(() => createHlnSkin({ id: "ok", tokens: { "--hln-ui-accent": "nope" } }), TypeError)
  const paired = createHlnSkin({
    id: "accent-pair",
    tokens: { "--hln-ui-accent": "#123456", "--hln-ui-on-accent": "#ffffff" },
  })
  assert.equal(paired.tokens["--hln-ui-on-accent"], "#ffffff")
})

