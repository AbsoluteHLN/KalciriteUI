test("v4 owns its focus ring: host chrome cannot repaint it, and it is never a wash", () => {
  const base = read("src/base.css")
  const folio = read("src/folio.css")
  const bundle = read("dist/hln-ui-system-v4.css")

  // A host rule such as `.shell :is(button, input, [tabindex]):focus-visible`
  // out-specifies the unscoped rule, so the engine ships a version-scoped one.
  const scoped =
    '[data-hln-ui-root][data-hln-ui-version="v4"] [data-hln-ui-control]:focus-visible'
  assert.ok(base.includes(scoped), "src/base.css missing the version-scoped focus rule")
  assert.ok(bundle.includes(scoped), "v4 bundle missing the version-scoped focus rule")

  // The composer clips overflow, so its indicator is an inset ring — and it
  // has to be solid: a 26% wash measures 1.54:1 against the paper.
  assert.ok(
    /\.hln-v4-composer__field:focus \{[^}]*box-shadow: inset 0 0 0 2px var\(--hln-ui-focus\)/.test(folio),
    "the composer focus indicator must be the solid inset focus ring",
  )
  assert.ok(
    !/\.hln-v4-composer__field:focus \{[^}]*color-mix\(in srgb, var\(--hln-ui-focus\) \d+%, transparent\)/.test(folio),
    "the composer focus indicator must not be a low-alpha wash",
  )

  // Every focus ring the engine paints is the focus token, never currentColor.
  assert.ok(
    !/outline:\s*2px solid currentColor/.test(bundle),
    "v4 bundle must not paint a focus ring with currentColor",
  )
})

test("v4 geometry stays inside the 8px contract cap", () => {
  const bundle = read("dist/hln-ui-system-v4.css")
  for (const match of bundle.matchAll(/border-radius:\s*([^;]+);/g)) {
    const value = match[1].trim()
    const px = value.match(/^([0-9.]+)px$/)
    if (!px) continue
    const size = Number(px[1])
    assert.ok(
      size <= 8 || size >= 999,
      `border-radius literal ${value} exceeds the 8px contract cap`,
    )
  }
  for (const match of bundle.matchAll(/--hln-ui-radius-[a-z-]+:\s*([^;]+);/g)) {
    const value = match[1].trim()
    const px = value.match(/^([0-9.]+)px$/)
    if (!px) continue
    const size = Number(px[1])
    assert.ok(
      size <= 8 || size >= 999,
      `radius token ${match[0].trim()} exceeds the 8px contract cap`,
    )
  }
})

