// ProjectHLN UI System v4.1 — Composite Build Script
// 合成顺序：tokens → components ⇒ dist/hln-ui-system-v4.1.css
import { mkdirSync, readFileSync, writeFileSync } from "node:fs"
import { dirname, join } from "node:path"
import { fileURLToPath } from "node:url"

const root = dirname(fileURLToPath(import.meta.url))
const srcDir = join(root, "src")
const distDir = join(root, "dist")

mkdirSync(distDir, { recursive: true })

const cssOrder = ["tokens.css", "components.css"]

const banner =
  "/* ProjectHLN UI System v4.1 — Composite: v3.2 skeleton + v3.3 overlay contract + partial v4 Folio absorption. Do not edit; generated by v4.1/build.mjs. */\n"
const bundle =
  banner + cssOrder.map((file) => readFileSync(join(srcDir, file), "utf8")).join("\n")

writeFileSync(join(distDir, "hln-ui-system-v4.1.css"), bundle, "utf8")
console.log("v4.1 dist assembled; bundle bytes:", Buffer.byteLength(bundle, "utf8"))
